import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.PREVIEW_URL || 'http://127.0.0.1:4321';
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
try{
  const page=await browser.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`${base}/?box=city&keep=one`);
  await page.locator('.flow-list-link').first().waitFor();
  assert.equal(await page.evaluate(()=>document.activeElement===document.body),true,'initial load must not steal focus');
  const first=page.locator('.flow-list-link').first();
  const name=await first.locator('.list-name > span').innerText();
  const share=await first.locator('strong').innerText();
  const accessibleName=await first.getAttribute('aria-label') ?? await first.innerText();
  assert.ok(accessibleName.includes(name));
  assert.ok(accessibleName.includes(share),'accessible name includes visible amount and percentage');
  assert.match(accessibleName,/\d+(?:\.\d+)?% of parent/);
  await first.focus();await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelector('.crumb-trail [aria-current="page"]')?.textContent?.trim()!== 'City of Chicago');
  await page.waitForFunction(()=>document.activeElement?.matches('.crumb-trail [aria-current="page"]'));
  assert.equal(await page.evaluate(()=>document.activeElement?.matches('.crumb-trail [aria-current="page"]')),true,'drill retains contextual focus');
  assert.equal(new URL(page.url()).searchParams.get('keep'),'one');
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>document.activeElement?.matches('.flow-list input, .flow-ribbons .ribbon, .flow-target, .crumb-trail button, .crumb-back')),true,'Tab remains near explorer context');
  await page.locator('.crumb-back').focus();await page.keyboard.press('Enter');
  await page.waitForFunction(()=>new URL(location.href).searchParams.get('box')==='city');
  await page.waitForFunction(()=>document.activeElement?.matches('.crumb-trail [aria-current="page"]'));
  assert.equal(await page.evaluate(()=>document.activeElement?.matches('.crumb-trail [aria-current="page"]')),true,'back retains focus');
  await page.locator('.crumb-back').focus();await page.keyboard.press('Enter');
  await page.waitForFunction(()=>!new URL(location.href).searchParams.has('box'));
  assert.equal(await page.evaluate(()=>document.activeElement?.matches('.root-option')),true,'all budgets focuses a root');
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>document.activeElement?.matches('.root-option')),true,'next Tab moves to adjacent root');
  await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelector('.crumb-trail [aria-current="page"]'));
  await page.waitForFunction(()=>document.activeElement?.matches('.crumb-trail [aria-current="page"]'));
  assert.equal(await page.evaluate(()=>document.activeElement?.matches('.crumb-trail [aria-current="page"]')),true,'root switch retains selected breadcrumb focus');
  await page.locator('.root-option[data-gov="parks"]').focus();await page.keyboard.press('Enter');
  await page.waitForFunction(()=>new URL(location.href).searchParams.get('box')==='parks');
  await page.waitForFunction(()=>document.querySelector('.crumb-trail [aria-current="page"]')?.textContent?.includes('Chicago Park District'));
  await page.waitForFunction(()=>document.querySelector('[data-status]')?.textContent?.includes('Showing Chicago Park District'));
  await page.waitForFunction(()=>document.activeElement?.matches('.crumb-trail [aria-current="page"]'));
  assert.equal(await page.evaluate(()=>document.activeElement?.matches('.crumb-trail [aria-current="page"]')),true,'switching roots retains focus');
  assert.deepEqual(errors,[]);
  console.log('Explorer keyboard focus and accessible names passed');
}finally{await browser.close()}
